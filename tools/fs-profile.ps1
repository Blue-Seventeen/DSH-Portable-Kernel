[CmdletBinding()]
param(
  [string]$Root = '',
  [string]$Out = '',
  [switch]$Force,
  [switch]$Quiet
)
# 识别便携壳所在卷的文件系统类型，并生成 tmp\fs-profile.cmd 供 .cmd 入口直接 call。
#
# 规则：
#   NTFS / ReFS  -> native 档：官方推荐的 workspace-write 沙箱 + pnpm 默认导入方式
#   exFAT / FAT32 / UNC / 其它 -> compat 档：关掉 ACL 沙箱（这类卷存不下安全描述符），
#                                pnpm 用 copy 导入（没有硬链接、没有软链）
#
# 只用 .NET DriveInfo 探测：不需要管理员、不需要 node，空壳（还没 bootstrap）也能跑。
# 探测失败不抛错：入口脚本会兜底成 compat。

$ErrorActionPreference = 'Stop'

if (-not $Root) {
  $Root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
}
$Root = $Root.TrimEnd('\', '/')
# 盘根（C: / G:）要补回斜杠：否则 GetPathRoot 拿不到卷根，NTFS 盘根会被误判成 OTHER/compat
if ($Root -match '^[A-Za-z]:$') { $Root = $Root + '\' }
try {
  $resolved = (Resolve-Path -LiteralPath $Root).Path
  # 盘根（C:\）只有 3 个字符，再 TrimEnd 就退回 "C:"，卷根本认不出来
  if ($resolved.Length -gt 3) { $Root = $resolved.TrimEnd('\') } else { $Root = $resolved }
} catch { }

$volumeRoot = [System.IO.Path]::GetPathRoot($Root)
$format = 'OTHER'
$driveLetter = ''
if ($volumeRoot -match '^([A-Za-z]):\\$') {
  $driveLetter = $Matches[1].ToUpperInvariant()
  try { $format = ([System.IO.DriveInfo]::new($volumeRoot)).DriveFormat } catch { $format = 'OTHER' }
} elseif ($volumeRoot -like '\\*') {
  $format = 'UNC'
}

$profile = 'compat'
switch ($format.ToUpperInvariant()) {
  'NTFS' { $profile = 'native' }
  'REFS' { $profile = 'native' }
}

# 排障开关：强制某一档，不写进默认行为
if ($env:DSH_PORTABLE_FORCE_PROFILE -match '(?i)^(native|compat)$') {
  $profile = $env:DSH_PORTABLE_FORCE_PROFILE.ToLowerInvariant()
}

$mode = if ($profile -eq 'native') { 'workspace-write' } else { 'danger-full-access' }
$importMethod = if ($profile -eq 'native') { 'auto' } else { 'copy' }

if (-not $Out) { $Out = Join-Path $Root 'tmp\fs-profile.cmd' }
$outDir = Split-Path -Parent $Out
if (-not (Test-Path -LiteralPath $outDir)) { New-Item -ItemType Directory -Path $outDir -Force | Out-Null }

# 卷序列号：同一盘符换了一块盘/换了格式时，只比盘符会沿用错档位
$serial = ''
try {
  $volOut = & fsutil fsinfo volumeinfo ($volumeRoot.TrimEnd('\')) 2>$null
  foreach ($line in @($volOut)) { if ($line -match 'Serial Number\s*:\s*(0x[0-9A-Fa-f]+)') { $serial = $Matches[1]; break } }
} catch { $serial = '' }

# 片段必须是纯 ASCII + CRLF（仓库铁律），且只做 set，不做判断
$lines = @(
  '@echo off',
  'rem generated by tools\fs-profile.ps1 - do not edit; delete it to force re-detection',
  ('set "DSH_FS_DRIVE=' + $driveLetter + '"'),
  ('set "DSH_FS_FORMAT=' + $format + '"'),
  ('set "DSH_FS_PROFILE=' + $profile + '"'),
  ('set "DSH_PERMISSION_MODE=' + $mode + '"'),
  ('set "DSH_PNPM_IMPORT_METHOD=' + $importMethod + '"'),
  ('set "DSH_FS_SERIAL=' + $serial + '"')
)
$body = ($lines -join "`r`n") + "`r`n"
$ascii = New-Object System.Text.ASCIIEncoding
[System.IO.File]::WriteAllText($Out, $body, $ascii)

# 缓存校验：盘符|卷序列号；env.cmd 用 for /f 读，任一不符就重探
[System.IO.File]::WriteAllText((Join-Path $outDir 'fs-drive.txt'), ($driveLetter + '|' + $serial + "`r`n"), $ascii)
if (-not $Quiet) {
  Write-Output ('fs-profile: volume=' + $volumeRoot + ' format=' + $format + ' profile=' + $profile + ' mode=' + $mode + ' import=' + $importMethod)
}